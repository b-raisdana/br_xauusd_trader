function BoolText($v) {
  $t = ("$v").Trim().ToLowerInvariant()
  if ($t -in @("1","true","yes","y")) { return "true" }
  return "false"
}
function Num([string]$v) {
  if ([string]::IsNullOrWhiteSpace($v)) { return 0.0 }
  return [double]::Parse($v,[Globalization.CultureInfo]::InvariantCulture)
}
function Parse-Time([string]$s) {
  $formats = @("yyyy.MM.dd HH:mm:ss.fff","yyyy.MM.dd HH:mm:ss")
  foreach($f in $formats){
    try { return [datetime]::ParseExact($s,$f,[Globalization.CultureInfo]::InvariantCulture) } catch {}
  }
  return [datetime]::Parse($s,[Globalization.CultureInfo]::InvariantCulture)
}
function Get-EnabledRangeDates([string]$CsvPath) {
  $ds = @()
  foreach($r in (Import-Csv $CsvPath)) {
    if([string]::IsNullOrWhiteSpace($r.date)){ continue }
    $enabled = ("$($r.enabled)").Trim().ToLowerInvariant()
    if($enabled -in @("false","0","no","n")){ continue }
    $ds += [datetime]::ParseExact($r.date,"yyyy.MM.dd",[Globalization.CultureInfo]::InvariantCulture)
  }
  return @($ds | Sort-Object -Unique)
}
function Resolve-DateRange($row,$AllRangeDates) {
  $scope = ("$($row.date_scope)").Trim().ToUpperInvariant()
  if($scope -eq "ALL_RANGES") {
    if($AllRangeDates.Count -eq 0){ Fail "ranges.csv contains no enabled dates" }
    $a = $AllRangeDates[0]
    $b = $AllRangeDates[$AllRangeDates.Count-1].AddDays(1)
    return @{ From=$a.ToString("yyyy.MM.dd"); To=$b.ToString("yyyy.MM.dd") }
  }
  if($scope -eq "CUSTOM") {
    $a = ("$($row.from_date)").Trim()
    $b = ("$($row.to_date)").Trim()
    if([string]::IsNullOrWhiteSpace($a) -or [string]::IsNullOrWhiteSpace($b)){
      Fail "CUSTOM date_scope requires from_date and to_date for run $($row.run_id)"
    }
    [void][datetime]::ParseExact($a,"yyyy.MM.dd",[Globalization.CultureInfo]::InvariantCulture)
    [void][datetime]::ParseExact($b,"yyyy.MM.dd",[Globalization.CultureInfo]::InvariantCulture)
    return @{ From=$a; To=$b }
  }
  return @{ From=$FromDate; To=$ToDate }
}
function Expected-Dates-InRange($AllRangeDates,[string]$A,[string]$B) {
  $from = [datetime]::ParseExact($A,"yyyy.MM.dd",[Globalization.CultureInfo]::InvariantCulture)
  $to = [datetime]::ParseExact($B,"yyyy.MM.dd",[Globalization.CultureInfo]::InvariantCulture)
  return @($AllRangeDates | Where-Object { $_ -ge $from -and $_ -lt $to } | ForEach-Object { $_.ToString("yyyy.MM.dd") })
}
