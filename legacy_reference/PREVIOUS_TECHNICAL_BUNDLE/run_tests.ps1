function Find-NewestOutput([string]$FileName,[datetime]$After) {
  # v1.1: TEST_MATRIX_IOFIX writes tester input/output with FILE_COMMON.
  # This avoids the local-agent sandbox being cleaned when the tester shuts down.
  $roots = @($CommonFilesDir) | Where-Object { Test-Path $_ }
  $hits = foreach ($r in $roots) {
    Get-ChildItem -Path $r -Recurse -File -Filter $FileName -ErrorAction SilentlyContinue |
      Where-Object { $_.LastWriteTime -ge $After.AddSeconds(-5) }
  }
  return $hits | Sort-Object LastWriteTime -Descending | Select-Object -First 1
}
function Save-Diagnostics([string]$RunDir,[datetime]$After) {
  $diagDir = Join-Path $RunDir "diagnostics"
  New-Item -ItemType Directory -Force -Path $diagDir | Out-Null
  $terminalLogDir = Join-Path $DataDir "Tester\logs"
  if(Test-Path $terminalLogDir){
    Get-ChildItem $terminalLogDir -File -Filter "*.log" -ErrorAction SilentlyContinue |
      Where-Object { $_.LastWriteTime -ge $After.AddMinutes(-2) } |
      ForEach-Object { Copy-Item $_.FullName (Join-Path $diagDir ("terminal_tester_"+$_.Name)) -Force }
  }
  # Agent root is normally under ...\MetaQuotes\Tester\<terminal-instance-id>.
  $instanceId = Split-Path $DataDir -Leaf
  $metaQuotesRoot = Split-Path (Split-Path $DataDir -Parent) -Parent
  $agentRoot = Join-Path $metaQuotesRoot "Tester\$instanceId"
  if(Test-Path $agentRoot){
    Get-ChildItem $agentRoot -Recurse -File -Filter "*.log" -ErrorAction SilentlyContinue |
      Where-Object { $_.LastWriteTime -ge $After.AddMinutes(-2) } |
      Select-Object -First 20 |
      ForEach-Object { Copy-Item $_.FullName (Join-Path $diagDir ("agent_"+$_.Directory.Name+"_"+$_.Name)) -Force }
  }
}
