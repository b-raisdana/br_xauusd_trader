if($matrix.Count -eq 0){ Fail "No enabled runs for phase $Phase" }

$allResults = @()
$allDaily = @()
$allChecks = @()
foreach($row in $matrix){
  $highMax = if($row.high_max -eq "USE_CANDIDATE"){$CandidateHighMax}else{[int]$row.high_max}
  $highSL  = if($row.high_sl -eq "USE_CANDIDATE"){$CandidateHighSL}else{Num $row.high_sl}
  $runId = $row.run_id
  $runDir = Join-Path $Root "results\$runId"
  New-Item -ItemType Directory -Force -Path $runDir | Out-Null
  $setName = "$runId.set"
  $setPathGenerated = Join-Path $Root "generated\$setName"
  $setMeta = Write-SetFile $row $setPathGenerated $highMax $highSL
  Copy-Item $setPathGenerated (Join-Path $testerProfiles $setName) -Force
  $iniPath = Join-Path $Root "generated\$runId.ini"
  $dr = Resolve-DateRange $row $allRangeDates
  $expectedDates = @(Expected-Dates-InRange $allRangeDates $dr.From $dr.To)
  Write-IniFile $row $setName $iniPath $dr.From $dr.To

  # v1.3 RESUME: reuse only locally archived evidence whose INI and SET exactly match
  # the current generated scenario. This avoids rerunning completed long tests while
  # preventing stale evidence from a different configuration being accepted.
  $resumeSummary = Join-Path $runDir $setMeta.Summary
  $resumeJournal = Join-Path $runDir $setMeta.Journal
  $resumeSet = Join-Path $runDir $setName
  $resumeIni = Join-Path $runDir "$runId.ini"
  $canResume = $false
  if($Resume -and (Test-Path $resumeSummary) -and (Test-Path $resumeJournal) -and (Test-Path $resumeSet) -and (Test-Path $resumeIni)) {
    $setSame = ((Get-FileHash $resumeSet -Algorithm SHA256).Hash -eq (Get-FileHash $setPathGenerated -Algorithm SHA256).Hash)
    $iniSame = ((Get-FileHash $resumeIni -Algorithm SHA256).Hash -eq (Get-FileHash $iniPath -Algorithm SHA256).Hash)
    if($setSame -and $iniSame) { $canResume = $true }
  }
  if($canResume) {
    Write-Host "[$($row.phase)] $runId : RESUME verified cached evidence" -ForegroundColor Cyan
    $base = Analyze-Summary $runId $row.phase (Num $row.deposit) $resumeSummary
    $analysis = Analyze-Extended $base $runId $row.phase (Num $row.deposit) (Num $row.lot) $highMax $highSL $dr.From $dr.To $resumeSummary $resumeJournal $expectedDates
    $res = $analysis.Summary
    $allResults += $res
    $allDaily += @($analysis.Daily)
    $allChecks += $analysis.Checks
    Write-Host "  -> cached PnL=$($res.net_pnl) Trades=$($res.trades) PF=$($res.profit_factor) QA=$($res.regression_status)" -ForegroundColor Green
    continue
  }

  # Remove stale shared outputs before the run; EA also deletes them on OnInit.
  Remove-Item (Join-Path $CommonFilesDir $setMeta.Summary) -Force -ErrorAction SilentlyContinue
  Remove-Item (Join-Path $CommonFilesDir $setMeta.Journal) -Force -ErrorAction SilentlyContinue
  Write-Host "[$($row.phase)] $runId : Deposit=$($row.deposit) GROSS15 Cap=$($row.max_live_positions) Restart=$($row.restart_time) Dates=$($dr.From)..$($dr.To)" -ForegroundColor Yellow
  $started = Get-Date
  Start-Process -FilePath $TerminalExe -ArgumentList "/config:`"$iniPath`"" -Wait | Out-Null

  $sumFile = Find-NewestOutput $setMeta.Summary $started
  $jourFile = Find-NewestOutput $setMeta.Journal $started
  if((-not $sumFile) -or (-not $jourFile)){
    Save-Diagnostics $runDir $started
    if($jourFile){ Copy-Item $jourFile.FullName (Join-Path $runDir $setMeta.Journal) -Force }
    $missing = @()
    if(-not $sumFile){ $missing += $setMeta.Summary }
    if(-not $jourFile){ $missing += $setMeta.Journal }
    Fail "$runId tester outputs missing from Common\Files: $($missing -join ', '). Diagnostics saved under results\$runId\diagnostics"
  }
  $sumDest = Join-Path $runDir $setMeta.Summary
  $jourDest = Join-Path $runDir $setMeta.Journal
  Copy-Item $sumFile.FullName $sumDest -Force
  Copy-Item $jourFile.FullName $jourDest -Force
  Copy-Item $iniPath $runDir -Force
  Copy-Item $setPathGenerated $runDir -Force
  $base = Analyze-Summary $runId $row.phase (Num $row.deposit) $sumDest
  $analysis = Analyze-Extended $base $runId $row.phase (Num $row.deposit) (Num $row.lot) $highMax $highSL $dr.From $dr.To $sumDest $jourDest $expectedDates
  $res = $analysis.Summary
  $allResults += $res
  $allDaily += @($analysis.Daily)
  $allChecks += $analysis.Checks
  Write-Host "  -> PnL=$($res.net_pnl) Trades=$($res.trades) PF=$($res.profit_factor) RevWR=$($res.reversal_win_rate)% PBWR=$($res.pullback_win_rate)% MaxPos=$($res.max_concurrent_positions) RiskUSD=$($res.peak_initial_risk_usd) Margin=$($res.max_account_margin) QA=$($res.regression_status)" -ForegroundColor Green
}

